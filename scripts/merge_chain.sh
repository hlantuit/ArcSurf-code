#!/bin/bash
# Merge chain on Albedo (template = the merge 36-40 chains). Run on a login node FROM scripts/:
#   bash merge_chain.sh <N> <src,src,...>
# 1. legend rules re-applied (idempotent): loess_reclass.py (loessoid Y -> E), ice_rich_reclass.py (ice_rich only where the
#    legend states ground ice) - new legends get the same treatment as the old ones
# 2. re-ingest + build_xw for every listed source (parallel; "xw:<src>" = crosswalk changed only), 3. merge <N> after all
#    crosswalks, 4. collect / web export /
#    coverage map after the merge, pending export after web + cov. Prints the job ids.
# merge_tiles.py REWRITES work/merge_sources.json at the end of every merge: check the list before running this.
set -e
N="$1"; SRCS="$2"
[ -n "$N" ] && [ -n "$SRCS" ] || { echo "usage: merge_chain.sh <N> <src,src,...>"; exit 1; }
cd /albedo/work/user/hlantuit/arctic_surficial/scripts
X="--export=ALL,SURF_DOMAIN=domain -A perm_ag_coas.perm_ag_coas -p smp --qos=12h"
PY=/albedo/work/user/hlantuit/conda_envs/arcticbeach/bin/python
$PY loess_reclass.py ../sources
$PY ice_rich_reclass.py ../sources
XW=""
for s in ${SRCS//,/ }; do
  case "$s" in
    ru_vsegei_pdf)     cmd="ingest_russia.py ru_vsegei_pdf"; t=06:00:00 ;;    # ~2.6 h; 3 h was too tight (merge 36)
    ru_vsegei_preview) cmd="ingest_russia.py ru_vsegei_preview"; t=03:00:00 ;;
    ru_vsegei_q2500)   cmd="ingest_russia.py ru_vsegei_q2500"; t=03:00:00 ;;
    ca_gsc_scans)      cmd="ingest_gsc_scans.py"; t=03:00:00 ;;
    ca_gsc_lines)      cmd="ingest_gsc_lines.py"; t=03:00:00 ;;
    us_usgs_sim3036)   cmd="ingest_alaska.py us_usgs_sim3036"; t=01:00:00 ;;   # crosswalk generated by classify_units
    us_ak_gems)        cmd="ingest_alaska.py us_ak_gems"; t=02:00:00 ;;        # idem
    us_usgs_sim3388)   cmd="ingest_alaska.py us_usgs_sim3388"; t=01:00:00 ;;   # copies the sim3340 crosswalk
    xw:*)              cmd=""; s=${s#xw:} ;;                                    # crosswalk changed only: build_xw
    *) echo "no ingest command for $s"; exit 1 ;;
  esac
  if [ -n "$cmd" ]; then
    a=$(sbatch --parsable $X -c 16 --mem=160G --time=$t -J ing_${s#*_}$N -o ../work/ing_${s}$N.out run_py.sh $cmd)
    x=$(sbatch --parsable $X -c 16 --mem=160G --time=02:00:00 -J xw_${s#*_}$N --dependency=afterok:$a -o ../work/xw_${s}$N.out run_py.sh build_xw.py $s)
  else
    a=none
    x=$(sbatch --parsable $X -c 16 --mem=160G --time=02:00:00 -J xw_${s#*_}$N -o ../work/xw_${s}$N.out run_py.sh build_xw.py $s)
  fi
  echo "$s: ingest $a xw $x"
  XW="$XW:$x"
done
SRC=$($PY -c "import json;print(','.join(json.load(open('../work/merge_sources.json'))))")
echo "merge sources: $(echo "$SRC" | tr ',' '\n' | wc -l)"
m=$(sbatch --parsable $X -c 32 --mem=160G --time=08:00:00 -J merge$N --dependency=afterok$XW -o ../work/merge$N.out --wrap "cd /albedo/work/user/hlantuit/arctic_surficial/scripts && rm -rf ../work/tiles && mv -f ../work/merge_tiles.log ../work/old/merge_tiles_run$((N-1)).log; $PY merge_tiles.py $SRC")
co=$(sbatch --parsable $X -c 32 --mem=160G --time=03:00:00 -J coll$N --dependency=afterok:$m -o ../work/coll$N.out run_py.sh merge_tiles.py --collect)
w=$(sbatch --parsable $X -c 32 --mem=160G --time=03:00:00 -J web$N --dependency=afterok:$m -o ../work/web$N.out run_py.sh export_coverage_web.py)
cv=$(sbatch --parsable $X -c 32 --mem=160G --time=03:00:00 -J cov$N --dependency=afterok:$m -o ../work/cov$N.out run_py.sh coverage_map.py)
p=$(sbatch --parsable $X -c 32 --mem=160G --time=03:00:00 -J pend$N --dependency=afterok:$w:$cv -o ../work/pend$N.out run_py.sh export_pending_web.py)
echo "merge$N $m coll $co web $w cov $cv pend $p"
